DROP TABLE IF EXISTS match_performance, match_umpire, matches, umpire,
                     season_sponsor, sponsor_industry, sponsor,
                     auction_player, player_team, auction, mentor,
                     player_role, player, team_season, team, stadium, season
                     CASCADE;

-- ---------------------------------------------------------------------
-- 1. SEASON
--    [FIX 9]  title_sponsor and total_matches removed (derived data:
--             see season_sponsor and COUNT(*) on matches)
--    [FIX 13] "year" renamed to season_year
-- ---------------------------------------------------------------------
CREATE TABLE season (
    season_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_year  INT  NOT NULL UNIQUE CHECK (season_year BETWEEN 2008 AND 2100),
    start_date   DATE NOT NULL,
    end_date     DATE NOT NULL,
    CONSTRAINT season_dates_chk CHECK (end_date > start_date)
);

-- ---------------------------------------------------------------------
-- 2. TEAM
-- ---------------------------------------------------------------------
CREATE TABLE team (
    team_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_name     VARCHAR(50) NOT NULL UNIQUE,
    home_city     VARCHAR(50) NOT NULL,
    coach_name    VARCHAR(50),
    owner_name    VARCHAR(80),
    founded_year  INT CHECK (founded_year BETWEEN 1900 AND 2100)
);

-- ---------------------------------------------------------------------
-- 3. TEAM_SEASON   (REGISTERED relationship)
--    [FIX 10] purse_total added: each team has its own auction purse
--             per season (default = 90 crore).  Spent / remaining
--             are derived in the v_team_purse view.
-- ---------------------------------------------------------------------
CREATE TABLE team_season (
    team_id      INT NOT NULL REFERENCES team(team_id)     ON DELETE RESTRICT,
    season_id    INT NOT NULL REFERENCES season(season_id) ON DELETE RESTRICT,
    purse_total  NUMERIC(14,2) NOT NULL DEFAULT 900000000 CHECK (purse_total >= 0),
    PRIMARY KEY (team_id, season_id)
);

-- ---------------------------------------------------------------------
-- 4. STADIUM
-- ---------------------------------------------------------------------
CREATE TABLE stadium (
    stadium_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stadium_name  VARCHAR(100) NOT NULL UNIQUE,
    city          VARCHAR(50)  NOT NULL,
    capacity      INT          NOT NULL CHECK (capacity > 0),
    pitch_type    VARCHAR(30)  CHECK (pitch_type IN
                    ('Batting','Bowling','Balanced','Spin-friendly'))
);

-- ---------------------------------------------------------------------
-- 5. PLAYER
--    [FIX 7]  jersey_no moved to player_team
--    [FIX 11] UNIQUE(player_name, dob) blocks duplicate registrations
--    Age is derived (see v_player_age view), never stored.
-- ---------------------------------------------------------------------
CREATE TABLE player (
    player_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_name    VARCHAR(60) NOT NULL,
    dob            DATE        NOT NULL CHECK (dob < CURRENT_DATE),
    nationality    VARCHAR(30) NOT NULL,
    batting_style  VARCHAR(30) CHECK (batting_style IN ('Right-hand','Left-hand')),
    bowling_style  VARCHAR(40),
    CONSTRAINT player_no_duplicate UNIQUE (player_name, dob)
);

-- multivalued attribute ROLE
CREATE TABLE player_role (
    player_id  INT NOT NULL REFERENCES player(player_id) ON DELETE CASCADE,
    role       VARCHAR(30) NOT NULL
               CHECK (role IN ('Batter','Bowler','All-rounder','Wicket-keeper')),
    PRIMARY KEY (player_id, role)
);

-- ---------------------------------------------------------------------
-- 6. MENTOR   (recursive MENTORS relationship)
--    [FIX 4]  this table was missing in the draft
-- ---------------------------------------------------------------------
CREATE TABLE mentor (
    mentor_id   INT NOT NULL REFERENCES player(player_id) ON DELETE CASCADE,
    mentee_id   INT NOT NULL REFERENCES player(player_id) ON DELETE CASCADE,
    start_date  DATE NOT NULL DEFAULT CURRENT_DATE,
    PRIMARY KEY (mentor_id, mentee_id),
    CONSTRAINT mentor_not_self CHECK (mentor_id <> mentee_id)
);

-- ---------------------------------------------------------------------
-- 7. AUCTION
--    budget removed: the purse now lives on team_season   [FIX 10]
-- ---------------------------------------------------------------------
CREATE TABLE auction (
    auction_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id     INT  NOT NULL REFERENCES season(season_id) ON DELETE RESTRICT,
    auction_date  DATE NOT NULL,
    venue         VARCHAR(100) NOT NULL
);

-- ---------------------------------------------------------------------
-- 8. PLAYER_TEAM   (SIGNS relationship)
--    [FIX 2]  PK is (player_id, season_id): one team per player per season
--    [FIX 2]  (team_id, season_id) must exist in team_season: a team can
--             only sign players for a season it is registered in
--    [FIX 7]  jersey_no lives here; price added; captain flag added
-- ---------------------------------------------------------------------
CREATE TABLE player_team (
    player_id   INT NOT NULL REFERENCES player(player_id) ON DELETE RESTRICT,
    season_id   INT NOT NULL,
    team_id     INT NOT NULL,
    jersey_no   INT CHECK (jersey_no BETWEEN 0 AND 99),
    price       NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
    is_captain  BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (player_id, season_id),
    FOREIGN KEY (team_id, season_id)
        REFERENCES team_season(team_id, season_id) ON DELETE RESTRICT,
    CONSTRAINT jersey_unique_in_squad UNIQUE (team_id, season_id, jersey_no)
);
-- at most one captain per team per season
CREATE UNIQUE INDEX one_captain_per_team_season
    ON player_team (team_id, season_id) WHERE is_captain;

-- ---------------------------------------------------------------------
-- 9. AUCTION_PLAYER   (APPLIES relationship)
--    [FIX 3]  base_price, sold_price, status, buying team added
-- ---------------------------------------------------------------------
CREATE TABLE auction_player (
    auction_id  INT NOT NULL REFERENCES auction(auction_id) ON DELETE CASCADE,
    player_id   INT NOT NULL REFERENCES player(player_id)   ON DELETE RESTRICT,
    base_price  NUMERIC(14,2) NOT NULL CHECK (base_price > 0),
    status      VARCHAR(10)   NOT NULL DEFAULT 'Pending'
                CHECK (status IN ('Pending','Sold','Unsold')),
    sold_price  NUMERIC(14,2),
    team_id     INT REFERENCES team(team_id) ON DELETE RESTRICT,
    PRIMARY KEY (auction_id, player_id),
    -- a Sold row must have a price >= base and a buyer; other rows must have neither
    CONSTRAINT auction_sale_chk CHECK (
        (status = 'Sold'
            AND sold_price IS NOT NULL AND sold_price >= base_price
            AND team_id IS NOT NULL)
     OR (status <> 'Sold' AND sold_price IS NULL AND team_id IS NULL)
    )
);

-- ---------------------------------------------------------------------
-- 10. SPONSOR  (+ multivalued INDUSTRY)
--     [FIX 8]  contract_value moved to season_sponsor
-- ---------------------------------------------------------------------
CREATE TABLE sponsor (
    sponsor_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE sponsor_industry (
    sponsor_id  INT NOT NULL REFERENCES sponsor(sponsor_id) ON DELETE CASCADE,
    industry    VARCHAR(50) NOT NULL,
    PRIMARY KEY (sponsor_id, industry)
);

-- ---------------------------------------------------------------------
-- 11. SEASON_SPONSOR   (SPONSORS relationship)
-- ---------------------------------------------------------------------
CREATE TABLE season_sponsor (
    season_id         INT NOT NULL REFERENCES season(season_id)   ON DELETE CASCADE,
    sponsor_id        INT NOT NULL REFERENCES sponsor(sponsor_id) ON DELETE RESTRICT,
    sponsorship_type  VARCHAR(30) NOT NULL
                      CHECK (sponsorship_type IN
                        ('Title','Associate','Official Partner','Broadcast','Kit')),
    contract_value    NUMERIC(14,2) NOT NULL CHECK (contract_value >= 0),
    start_date        DATE NOT NULL,
    end_date          DATE NOT NULL,
    PRIMARY KEY (season_id, sponsor_id),
    CONSTRAINT sponsorship_dates_chk CHECK (end_date > start_date)
);
-- only one title sponsor per season
CREATE UNIQUE INDEX one_title_sponsor_per_season
    ON season_sponsor (season_id) WHERE sponsorship_type = 'Title';

-- ---------------------------------------------------------------------
-- 12. MATCHES   (renamed from MATCH)                         [FIX 1]
--     [FIX 6]  every match rule is enforced declaratively
-- ---------------------------------------------------------------------
CREATE TABLE matches (
    match_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id       INT  NOT NULL,
    stadium_id      INT  NOT NULL REFERENCES stadium(stadium_id) ON DELETE RESTRICT,
    match_date      DATE NOT NULL,
    match_time      TIME NOT NULL,
    match_type      VARCHAR(20) NOT NULL DEFAULT 'League'
                    CHECK (match_type IN
                      ('League','Qualifier 1','Eliminator','Qualifier 2','Final')),
    team1_id        INT NOT NULL,
    team2_id        INT NOT NULL,
    toss_winner_id  INT,
    winner_id       INT,
    status          VARCHAR(12) NOT NULL DEFAULT 'Scheduled'
                    CHECK (status IN ('Scheduled','Completed','No Result')),
    result_text     VARCHAR(100),
    man_of_match_id INT REFERENCES player(player_id) ON DELETE SET NULL,

    -- both teams must be registered for THIS season
    FOREIGN KEY (team1_id, season_id) REFERENCES team_season(team_id, season_id),
    FOREIGN KEY (team2_id, season_id) REFERENCES team_season(team_id, season_id),
    FOREIGN KEY (toss_winner_id) REFERENCES team(team_id),
    FOREIGN KEY (winner_id)      REFERENCES team(team_id),

    CONSTRAINT two_different_teams CHECK (team1_id <> team2_id),
    CONSTRAINT toss_is_a_playing_team
        CHECK (toss_winner_id IS NULL OR toss_winner_id IN (team1_id, team2_id)),
    CONSTRAINT winner_is_a_playing_team
        CHECK (winner_id IS NULL OR winner_id IN (team1_id, team2_id)),
    -- Completed => has a winner ; Scheduled / No Result => no winner
    CONSTRAINT status_matches_winner CHECK (
        (status = 'Completed' AND winner_id IS NOT NULL)
     OR (status <> 'Completed' AND winner_id IS NULL)),
    -- a stadium cannot host two matches at the same date and time
    CONSTRAINT stadium_not_double_booked UNIQUE (stadium_id, match_date, match_time)
);

-- ---------------------------------------------------------------------
-- 13. MATCH_PERFORMANCE   (weak entity, PK = match_id + player_id)
--     [FIX 5]  runs_conceded added; strike_rate and economy are now
--              GENERATED columns (cannot go out of sync).
--     overs is stored in cricket notation: 3.4 = 3 overs 4 balls.
-- ---------------------------------------------------------------------
CREATE TABLE match_performance (
    match_id        INT NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    player_id       INT NOT NULL REFERENCES player(player_id) ON DELETE RESTRICT,
    runs            INT NOT NULL DEFAULT 0 CHECK (runs >= 0),
    balls           INT NOT NULL DEFAULT 0 CHECK (balls >= 0),
    wickets         INT NOT NULL DEFAULT 0 CHECK (wickets BETWEEN 0 AND 10),
    overs           NUMERIC(3,1) NOT NULL DEFAULT 0
                    CHECK (overs >= 0 AND overs <= 4
                           AND MOD((overs * 10)::INT, 10) <= 5),
    runs_conceded   INT NOT NULL DEFAULT 0 CHECK (runs_conceded >= 0),
    catches         INT NOT NULL DEFAULT 0 CHECK (catches >= 0),

    -- derived values
    strike_rate NUMERIC(6,2) GENERATED ALWAYS AS (
        CASE WHEN balls > 0 THEN ROUND(runs * 100.0 / balls, 2) END
    ) STORED,
    economy NUMERIC(5,2) GENERATED ALWAYS AS (
        CASE WHEN overs > 0 THEN ROUND(
            runs_conceded * 6.0
            / (FLOOR(overs) * 6 + MOD((overs * 10)::INT, 10)), 2) END
    ) STORED,

    PRIMARY KEY (match_id, player_id)
);

-- ---------------------------------------------------------------------
-- 14. UMPIRE
-- ---------------------------------------------------------------------
CREATE TABLE umpire (
    umpire_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    umpire_name       VARCHAR(60) NOT NULL,
    nationality       VARCHAR(30) NOT NULL,
    experience_years  INT NOT NULL DEFAULT 0 CHECK (experience_years >= 0)
);

-- ---------------------------------------------------------------------
-- 15. MATCH_UMPIRE   (OFFICIATES relationship, was REVIEWS)
--     The "at least 2 on-field umpires" rule is in triggers.sql.
-- ---------------------------------------------------------------------
CREATE TABLE match_umpire (
    match_id   INT NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    umpire_id  INT NOT NULL REFERENCES umpire(umpire_id) ON DELETE RESTRICT,
    role       VARCHAR(12) NOT NULL
               CHECK (role IN ('On-field','Third','Reserve')),
    fee        NUMERIC(10,2) NOT NULL CHECK (fee >= 0),
    PRIMARY KEY (match_id, umpire_id)
);

